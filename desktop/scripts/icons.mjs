// Writes src/Anima/Desktop/Icons.hs from the lucide icons the browser uses, so both draw
// the same marks. Run from desktop/: node scripts/icons.mjs (needs web/node_modules).
import { readFileSync, writeFileSync } from "node:fs";

const names = {
  back: "arrow-left", undo: "undo-2", redo: "redo-2", connection: "plug", chat: "panel-right",
  select: "mouse-pointer-2", pen: "pen-line", pencil: "pencil", marker: "highlighter", paint: "paintbrush",
  grass: "sprout", birds: "bird", stars: "sparkles", leaves: "leaf", flowers: "flower-2", spray: "spray-can",
  eraser: "eraser", shapes: "shapes", line: "minus", rect: "square", ellipse: "circle", triangle: "triangle",
  fill: "paint-bucket", text: "type", prev: "chevron-left", next: "chevron-right", play: "play", pause: "pause",
  add: "plus", minus: "minus", duplicate: "copy", remove: "trash-2", onion: "layers", eye: "eye", eyeOff: "eye-off",
  lock: "lock", unlock: "lock-open", fit: "scan", image: "image", newDrawing: "square-plus", newLayer: "copy-plus",
  folder: "folder-open", server: "server", light: "lightbulb", hold: "move-horizontal",
  pin: "pin", eyedropper: "pipette", trace: "hand", film: "film", references: "images",
  settings: "settings-2", newChat: "square-pen", send: "arrow-up", stop: "square", step: "check", alert: "circle-alert", up: "arrow-up", down: "arrow-down", camera: "camera",
};

const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(" ");
const out = [];
for (const [key, file] of Object.entries(names)) {
  const src = readFileSync(`../web/node_modules/lucide/dist/esm/icons/${file}.js`, "utf8");
  const body = src.slice(src.indexOf("= [") + 2, src.lastIndexOf("];") + 1);
  const nodes = JSON.parse(body.replace(/(\w+):/g, '"$1":').replace(/,\s*\]/g, "]").replace(/,\s*\}/g, "}"));
  const inner = nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join("");
  out.push(`("${key}", "${inner.replaceAll('"', '\\"')}")`);
}

writeFileSync(
  "src/Anima/Desktop/Icons.hs",
  `{- | The lucide icons (ISC licence) the window uses, the same marks as the browser's;
generated by @scripts/icons.mjs@. Each is the inside of a 24 × 24 SVG, stroked in the
colour asked for.
-}
module Anima.Desktop.Icons (iconSvg) where

import Data.Text (Text)

import Data.Map.Strict qualified as Map

-- | A whole SVG document for icon \`name\`, stroked in \`colour\` (a CSS colour).
iconSvg :: Text -> Text -> Maybe Text
iconSvg colour name = wrap <$> Map.lookup name icons
    where
        wrap inner = "<svg xmlns=\\"http://www.w3.org/2000/svg\\" width=\\"24\\" height=\\"24\\" viewBox=\\"0 0 24 24\\" fill=\\"none\\" stroke=\\"" <> colour <> "\\" stroke-width=\\"1.75\\" stroke-linecap=\\"round\\" stroke-linejoin=\\"round\\">" <> inner <> "</svg>"

icons :: Map.Map Text Text
icons =
    Map.fromList
        [ ${out.join("\n        , ")}
        ]
`,
);
console.log(`${Object.keys(names).length} icons`);
